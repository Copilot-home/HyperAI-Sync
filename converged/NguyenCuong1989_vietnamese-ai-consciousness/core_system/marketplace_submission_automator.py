    def _validate_extension(self):
        """Validate extension package"""
        print("\n🔍 Validating extension package...")

        extension_path = self.project_root / self.extension_package

        if not extension_path.exists():
            print(f"⚠  Extension package not found: {extension_path}")
            print("🔧 Attempting to create extension package...")

            # Try to create the extension package
            try:
                # Check if we have the extension source
                extension_dir = self.project_root / "extension"
                if extension_dir.exists():
                    # Run vsce package command
                    result = subprocess.run(["npx", "vsce", "package", "--out", str(extension_path)], cwd=str(extension_dir), capture_output=True, text=True)

                    if result.returncode == 0:
                        print(" Extension package created successfully")
                    else:
                        print(f" Failed to create extension package: {result.stderr}")
                        raise Exception("Extension packaging failed")
                else:
                    raise FileNotFoundError("Extension source directory not found")

            except Exception as e:
                print(f" Could not create extension package: {str(e)}")
                print("📋 Please ensure the extension source is available and try again")
                return

        # Validate package size
        size_mb = extension_path.stat().st_size / (1024 * 1024)
        if size_mb > 100:
            raise ValueError(f"Extension too large: {size_mb:.2f}MB (max 100MB)")

        print(f" Extension validated: {size_mb:.2f}MB")

        # Test extension installation
        print("🧪 Testing extension installation...")
        test_command = f'code --install-extension "{extension_path}" --force'
        result = subprocess.run(test_command, shell=True, capture_output=True, text=True)

        if result.returncode == 0:
            print(" Extension installed successfully")
        else:
            print(f"⚠  Extension installation warning: {result.stderr}")

        self.submission_status["extension_validated"] = True

